#!/usr/bin/env node
/**
 * Generate the committed header images for micro-foresight's seeded questions.
 *
 *   cd deploy
 *   ./scripts/foresight-covers.mjs --plan            # what WOULD be generated; no credential read
 *   ./scripts/foresight-covers.mjs                   # generate everything missing
 *   ./scripts/foresight-covers.mjs --only btc,fomc   # a subset, matched loosely
 *   ./scripts/foresight-covers.mjs --limit 3         # the budget control
 *   ./scripts/foresight-covers.mjs --only <slug> --force   # regenerate ONE, deliberately
 *
 * ── WHY THIS EXISTS AS A SCRIPT RATHER THAN AS SOMETHING SOMEBODY TYPED ──────
 *
 * `assets/seed/foresight/*.png` are committed art, and `scripts/seed/
 * foresight.mjs` adopts them by slug. The nine that were there before this file
 * were generated by hand against the live Azure resource on 2026-08-05, and what
 * was NOT recorded anywhere is the prompt each was generated from. That is the
 * gap this closes: every image below is produced from a prompt that is written
 * into `assets/seed/foresight/COVERS.json` beside its sha256, so a reviewer can
 * read what was asked for rather than infer it from the picture.
 *
 * The conventions are `brand/generate.ts`'s, deliberately, because that harness
 * has already been argued about at length:
 *
 *   * the prompt is ON RECORD in a manifest, per asset, verbatim;
 *   * the run is RESUME-SAFE — the manifest is rewritten after every single
 *     image, so an interrupt loses at most one;
 *   * `--force` regenerates something already recorded, and counts as a retry.
 *
 * ── THE TWO PLACES IT DIVERGES FROM `brand/generate.ts`, AND WHY ─────────────
 *
 * **1. The resume rule reads the DISK as well as the manifest.** In `brand/`
 * the manifest is the sole authority, which is right there because the manifest
 * and the pixels were written by the same program. Here nine PNGs predate the
 * manifest entirely. A manifest-only rule would have regenerated all nine on the
 * first run — real money, and a silent rewrite of art nobody asked to change.
 * `scripts/seed/images.mjs` states the estate rule in capitals ("NO FLUX ASSET
 * IN THIS TREE IS EVER WRITTEN, MOVED, OVERWRITTEN OR REGENERATED"), so a file
 * on disk counts as done and gets a manifest entry describing what is and is not
 * known about it.
 *
 * **2. `--force` refuses to run without `--only`.** In `brand/` a global force
 * is a bounded amount of money over a fixed asset list. Here it is every cover
 * for every seeded question, including the nine whose prompts were never
 * recorded and which therefore cannot be reproduced — a blanket `--force` would
 * replace art that cannot be got back. Naming what to regenerate is one extra
 * word and it is the difference between an intent and an accident.
 *
 * ── THE PROMPT IS studio's, COPIED AND CORRECTED ────────────────────────────
 *
 * `studio/src/prompt.ts` owns the art direction for the `cover` kind, and this
 * file reproduces its structure — style, then composition, then subject, then
 * prohibitions — so that a committed cover and one `generateCover` produces at
 * seed time are the same kind of picture. It is a copy rather than an import
 * because this repository imports no sibling TypeScript;
 * `scripts/seed/foresight-questions.mjs` sets out that argument for the question
 * data and it applies unchanged here.
 *
 * `COMPOSITION.cover` and `NO_TEXT` are verbatim. The style paragraph is NOT:
 * it corrects the ground colour to the one the committed covers actually use and
 * hardens the demand for flat vector art. Both changes are measurements rather
 * than opinions and both are argued at their definitions below — see `GROUND`
 * and `coverStyle`. The short version is that studio's literal ground is nearly
 * black, the nine covers already on disk are pale stone, and a browse page
 * showing both is the thing this script exists to avoid.
 *
 * A copy can drift, so the defence is not that it will not: it is that the FULL
 * prompt actually sent is recorded per asset in COVERS.json. A reviewer never
 * has to trust this file's account of its own prompt, because the bytes and the
 * string that produced them are recorded together.
 *
 * ── ABOUT THE CREDENTIAL ────────────────────────────────────────────────────
 *
 * Read from `../studio/.env.local`, which is gitignored in that repository and
 * is the estate's one credential file for image generation. Nothing here prints
 * an environment variable's value, and nothing here prints a caught error's
 * message — Node's `fetch` puts the whole request URL, query string included,
 * into the exception, and that URL names the Azure resource. Only the error's
 * CLASS NAME and `cause.code` are ever reported, which is `brand/backends.ts`'s
 * rule and it is there because the alternative has leaked a credential twice in
 * this estate.
 */

